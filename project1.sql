#4  ● What are the monthly trends in order volume and revenue?

SELECT 
    COUNT(DISTINCT od.ord_id) AS orders,
    SUM(od.total_price) AS revenue,MONTH(STR_TO_DATE(o.order_date, '%m/%d/%Y')) AS mn
FROM
    orders o
        JOIN
    order_details od ON o.ord_id = od.ord_id
