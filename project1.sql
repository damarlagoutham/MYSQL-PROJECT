 #3 ● What is the total sales value processed by each employee?
 SELECT 
    e.emp_id, e.emp_name, SUM(d.total_price) AS total_sales
FROM
    employees e
        JOIN
    orders o ON e.emp_id = o.emp_id
        JOIN
    order_details d ON o.ord_id = d.ord_id
GROUP BY e.emp_id , e.emp_name
ORDER BY total_sales DESC;
        
        
#4 ● What is the average order value handled per employee?
SELECT 
    e.emp_id, e.emp_name, AVG(x.total_o) AS avg_o_v
FROM
    employees e
        JOIN
    (SELECT 
        o.emp_id, o.ord_id, SUM(d.total_price) AS total_o
    FROM
        orders o
    JOIN order_details d ON o.ord_id = d.ord_id
    GROUP BY o.emp_id , o.ord_id) x ON e.emp_id = x.emp_id
GROUP BY e.emp_id , e.emp_name;

    
