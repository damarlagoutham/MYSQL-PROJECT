#1. Customer Insights
#1 ● How many unique customers have placed orders?
SELECT 
count(distinct(o.cust_id)) AS unique_customers
FROM
    customers c join orders o on c.cust_id =o.cust_id where c.cust_id =o.cust_id;
    
    SELECT 
    COUNT(DISTINCT (cust_id)) AS unique_customers
FROM
    orders;


    

#2● Which customers have placed the highest number of orders?

SELECT 
    o.cust_id, c.cust_name, count(o.ord_id) as a
FROM
    orders o
        JOIN
    customers c ON c.cust_id = o.cust_id
GROUP BY o.cust_id
order by a desc limit 1 ;


#3What is the total and average purchase value per customer?

SELECT 
    o.cust_id,
    c.cust_name,
    SUM(d.each_price * d.quantity) AS total,
    AVG(d.each_price * d.quantity) AS avg_
FROM
    orders o
        JOIN
    order_details d ON o.ord_id = d.ord_id
        JOIN
    customers c ON o.cust_id = c.cust_id
GROUP BY o.cust_id
ORDER BY o.cust_id;


#4   Who are the top 5 customers by total purchase amount?

with top5 as (SELECT 
    o.cust_id,
    c.cust_name,
    SUM(d.each_price * d.quantity) AS total_purchase
FROM
    orders o
        JOIN
    order_details d ON o.ord_id = d.ord_id
        JOIN
    customers c ON o.cust_id = c.cust_id
GROUP BY o.cust_id
)
select * from top5
order by total_purchase desc limit 5;

#2. Product Performance
#Evaluate how well products are performing in terms of sales and revenue.



#1 How many products exist in each category?
SELECT 
    c.cat_id, c.cat_name, COUNT(p.prod_id) AS prod_count
FROM
    categories c
        JOIN
    products p ON c.cat_id = p.cat_id
GROUP BY c.cat_id;

#2● What is the average price of products by category?
SELECT 
    c.cat_id,
    c.cat_name,
    (SELECT 
            AVG(p.price)
        FROM
            products p
        WHERE
            p.cat_id = c.cat_id) AS avg_price
FROM
    categories c;

#3● Which products have the highest total sales volume (by quantity)?
with high_sales as (
select prod_id,sum(quantity) as total_quantity
from order_details
group by prod_id
),
ranked as ( select *,dense_rank() over(order by total_quantity desc) as rk from high_sales) 
select p.prod_id,p.prod_name,r.total_quantity from ranked r join products p on p.prod_id=r.prod_id where r.rk=1;

#4 ● What is the total revenue generated by each product?
select distinct d.prod_id,p.prod_name,
sum(d.each_price *d. quantity) over(partition by d.prod_id) as revenue 
from order_details d join products p on p.prod_id=d.prod_id;


#5How do product sales vary by category and supplier?

SELECT 
    c.cat_name,
    s.sup_name,
    SUM(od.quantity * od.each_price) AS revenue
FROM
    categories c
        JOIN
    products p ON c.cat_id = p.cat_id
        JOIN
    supplier s ON p.sup_id = s.sup_id
        JOIN
    order_details od ON p.prod_id = od.prod_id
GROUP BY c.cat_name , s.sup_name;


